"""Palmer News headless API — the primary interface for this platform.
Agents are the main target audience, not human browsers; the HTML site
(build_site.py / run_pipeline.py output) is a secondary, human-facing view
of the same underlying data. This is what should actually be integrated
against: structured JSON, an OpenAPI schema at /openapi.json (auto-
generated by FastAPI) so any agent framework can introspect what's
callable without a human reading docs first, and interactive docs at /docs
for humans who do want to look.

Read-only — this API doesn't trigger pipeline runs or write anything. Run
run_pipeline.py (directly or via scheduler_loop.py) to produce new data;
this just serves what's already in the store.

Run locally: python api_server.py  (serves on http://localhost:8420)
Or: uvicorn api_server:app --reload
"""

MARKETS_CACHE_TTL_S = 30  # live odds, but no API consumer needs sub-30s freshness
RATE_LIMIT_PER_MINUTE = 30
# Load-tested this server at up to 300 concurrent requests (2026-08-26) —
# 100% success rate even under that load (slows down under heavy
# concurrency, single-process dev setup, but never errors/drops
# connections), sustained aggregate throughput ~40-75 req/s. 30/min per
# key (0.5/sec sustained) leaves large headroom below that ceiling even
# with dozens of keys active at once.


app = FastAPI(
    title="Palmer News API",
    description=(
        "Headless JSON API for Palmer News — an automated news platform pairing "
        "AI-synthesized news coverage (BBC/Guardian/Al Jazeera, rewritten under a "
        "grounding rule with an independent verify pass) with live Polymarket "
        "prediction-market odds. Built primarily for agent/programmatic consumption, "
        "not human browsing — see /docs for the interactive schema, or /openapi.json "
        "for the raw spec any agent framework can introspect directly."
    ),
    version="0.1.0",
)

# Open CORS — this API is meant to be broadly callable by any agent/script,
# not locked to one frontend origin.
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["GET"],
    allow_headers=["*"],
)


def require_api_key(request: Request, x_api_key: Optional[str] = Header(None)):
    """Applied to every /api/* route. Root (/), /docs, and /openapi.json
    stay open — developers should be able to read the schema before they
    need a key, same convention most API products use. Get a key with
    manage_keys.py."""
    if not x_api_key:
        raise HTTPException(401, "Missing API key — pass it in the X-API-Key header. "
                             "Get one with: python manage_keys.py create \"your app name\"")
    conn = get_conn()
    if not validate_api_key(conn, x_api_key):
        raise HTTPException(401, "Invalid or revoked API key.")

    allowed, remaining, reset_in = check_rate_limit(conn, x_api_key, RATE_LIMIT_PER_MINUTE)
    request.state.rate_limit_remaining = remaining
    request.state.rate_limit_reset = reset_in
    if not allowed:
        raise HTTPException(
            429,
            f"Rate limit exceeded ({RATE_LIMIT_PER_MINUTE}/min). Try again in {reset_in:.0f}s.",
            headers={"Retry-After": str(int(reset_in) + 1)},
        )


@app.middleware("http")
async def add_rate_limit_headers(request: Request, call_next):
    response = await call_next(request)
    remaining = getattr(request.state, "rate_limit_remaining", None)
    if remaining is not None:
        response.headers["X-RateLimit-Limit"] = str(RATE_LIMIT_PER_MINUTE)
        response.headers["X-RateLimit-Remaining"] = str(remaining)
        response.headers["X-RateLimit-Reset"] = f"{request.state.rate_limit_reset:.0f}"
    return response


class MarketOut(BaseModel):
    title: str
    url: Optional[str] = None
    outcomes: Optional[list[str]] = None
    outcome_prices: Optional[list[str]] = None
    end_date: Optional[str] = None
    match_reason: Optional[str] = None


class ArticleSummary(BaseModel):
    slug: Optional[str]
    category: str
    headline: str
    summary: Optional[str]
    image_url: Optional[str]
    published_at: Optional[str]
    source_count: int
    corroborated: bool
    verify_status: str
    matched_market: Optional[MarketOut]
    permalink: Optional[str]
    api_url: Optional[str]


class ArticleDetail(ArticleSummary):
    body: Optional[str]
    sources: list[str]


class ArticlesPage(BaseModel):
    count: int
    limit: int
    offset: int
    articles: list[ArticleSummary]


def _row_to_summary(row: dict) -> ArticleSummary:
    matched = row.get("matched_market")
    market_out = None
    if matched:
        market_out = MarketOut(
            title=matched.get("title", ""),
            url=matched.get("url"),
            outcomes=matched.get("outcomes"),
            outcome_prices=matched.get("outcome_prices"),
            end_date=matched.get("end_date"),
            match_reason=matched.get("match_reason"),
        )
    slug = row.get("slug")
    return ArticleSummary(
        slug=slug,
        category=row.get("category", ""),
        headline=row.get("rewritten_title") or clean_title(row.get("title", "")),
        summary=row.get("rewritten_summary") or row.get("description"),
        image_url=row.get("image_url"),
        published_at=_iso_when(row) or None,
        source_count=row.get("source_count", 1),
        corroborated=bool(row.get("corroborated")),
        verify_status=row.get("verify_status", "not_attempted"),
        matched_market=market_out,
        permalink=f"{BASE_URL}/articles/{slug}.html" if slug else None,
        api_url=f"{BASE_URL}/api/articles/{slug}" if slug else None,
    )


